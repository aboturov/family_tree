import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { patronymicFor, patronymicFrom } from '../src/patronymic.ts';

describe('отчество', () => {
  it('по имени отца', () => {
    const cases: [string, string, string][] = [
      ['Василий', 'Васильевич', 'Васильевна'],
      ['Юрий', 'Юрьевич', 'Юрьевна'],
      ['Евгений', 'Евгеньевич', 'Евгеньевна'],
      ['Дмитрий', 'Дмитриевич', 'Дмитриевна'],
      ['Георгий', 'Георгиевич', 'Георгиевна'],
      ['Николай', 'Николаевич', 'Николаевна'],
      ['Сергей', 'Сергеевич', 'Сергеевна'],
      ['Алексей', 'Алексеевич', 'Алексеевна'],
      ['Игорь', 'Игоревич', 'Игоревна'],
      ['Владимир', 'Владимирович', 'Владимировна'],
      ['Александр', 'Александрович', 'Александровна'],
      ['Михаил', 'Михайлович', 'Михайловна'],
      ['Павел', 'Павлович', 'Павловна'],
      ['Лев', 'Львович', 'Львовна'],
      ['Илья', 'Ильич', 'Ильинична'],
      ['Кузьма', 'Кузьмич', 'Кузьминична'],
      ['Никита', 'Никитич', 'Никитична'],
      ['Фёдор', 'Фёдорович', 'Фёдоровна'],
      ['Олег', 'Олегович', 'Олеговна'],
    ];
    for (const [name, m, f] of cases) {
      assert.equal(patronymicFrom(name, 'M'), m, name);
      assert.equal(patronymicFrom(name, 'F'), f, name);
    }
    assert.equal(patronymicFrom('', 'M'), '');
  });

  it('в другом роде — для брата и сестры', () => {
    assert.equal(patronymicFor('Васильевич', 'F'), 'Васильевна');
    assert.equal(patronymicFor('Васильевна', 'M'), 'Васильевич');
    assert.equal(patronymicFor('Ильич', 'F'), 'Ильинична');
    assert.equal(patronymicFor('Кузьминична', 'M'), 'Кузьмич');
    assert.equal(patronymicFor('Никитична', 'M'), 'Никитич');
    assert.equal(patronymicFor('Игоревич', 'M'), 'Игоревич');
  });
});
